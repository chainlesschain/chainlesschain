// Real CLI stdout shared by both IDE hosts. Regeneration intentionally changes
// event hashes/timestamps; no fixture identity is invented by this script.
import { execFileSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = mkdtempSync(join(tmpdir(), "cc-transcript-fixture-"));
process.env.CHAINLESSCHAIN_HOME = join(root, "home");
process.env.CHAINLESSCHAIN_SECURITY_ANCHOR_HOME = join(root, "security");
try {
  const store = await import("../src/harness/jsonl-session-store.js");
  const { HISTORY_PREFIX_SCHEMA } =
    await import("../src/lib/session-history-origins.js");
  const sessionId = "fixture-history-sync";
  const cli = fileURLToPath(
    new URL("../bin/chainlesschain.js", import.meta.url),
  );
  const query = (after, size = 2) =>
    JSON.parse(
      execFileSync(
        process.execPath,
        [
          cli,
          "session",
          "show",
          "--json",
          "--history",
          "--page-size",
          String(size),
          ...(after ? ["--after", after] : []),
          "--",
          sessionId,
        ],
        { encoding: "utf8", env: process.env, timeout: 30_000 },
      ),
    );
  store.startSession(sessionId, { provider: "fixture", model: "fixture" });
  const refs = [];
  let baseline;
  for (let turn = 0; turn < 3; turn++) {
    const user = store.appendUserMessage(sessionId, "same 中文😀");
    const assistant = store.appendAssistantMessage(sessionId, "same 中文😀");
    refs.push({
      schema: "chainlesschain.session-transcript-references/v1",
      sessionId,
      userEventId: user.hash,
      assistantEventId: assistant.hash,
      clientMessageId: `fixture-${turn}`,
    });
    if (turn === 0) baseline = query();
  }
  const first = query(baseline.syncCursor);
  const second = query(first.nextCursor);
  store.appendEvent(sessionId, "token_usage", {
    input_tokens: 5,
    output_tokens: 2,
  });
  const metadata = query(second.nextCursor);
  const messages = store.readVerifiedMessages(sessionId);
  const head = store.findLatestEvent(sessionId, null).hash;
  store.withSessionAuthorityTransaction(sessionId, head, (transaction) =>
    transaction.appendAuthorityEvent("checkpoint_timeline_commit", {
      action: "restore-conversation",
      messages: messages.slice(0, 2),
      historyPrefix: {
        schema: HISTORY_PREFIX_SCHEMA,
        sourceHead: transaction.currentHeadHash(),
        sourceMessageCount: messages.length,
        retainedMessageCount: 2,
      },
      binding: { turns: [] },
    }),
  );
  const rewind = query();
  for (let i = 0; i < 18; i++)
    store.appendAssistantMessage(sessionId, `continued ${i}`);
  const continuation = [];
  let cursor = rewind.syncCursor;
  do {
    const batch = query(cursor);
    continuation.push(batch);
    cursor = batch.nextCursor;
  } while (continuation.at(-1).hasMore);
  writeFileSync(
    new URL(
      "../__tests__/fixtures/session-transcript-sync-v1.json",
      import.meta.url,
    ),
    JSON.stringify(
      {
        source:
          "Actual cc session show stdout from an isolated canonical store; generated by scripts/generate-transcript-sync-fixture.mjs",
        sessionId,
        baseline,
        first,
        second,
        metadata,
        rewind,
        refs,
        continuation,
      },
      null,
      2,
    ) + "\n",
  );
} finally {
  rmSync(root, { recursive: true, force: true });
}
