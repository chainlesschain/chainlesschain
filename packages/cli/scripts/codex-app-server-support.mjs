#!/usr/bin/env node
import {
  appendFileSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  CODEX_APP_SERVER_FEATURE_FLAG,
  CODEX_APP_SERVER_FALLBACK_PROTOCOL,
  CODEX_APP_SERVER_SUPPORT,
  codexAppServerCiMatrices,
  getCodexAppServerSupport,
} from "../src/lib/codex-app-server-support.js";

export function renderCodexAppServerSupport() {
  const rows = CODEX_APP_SERVER_SUPPORT.versions.map(
    (entry) =>
      `| ${entry.version} | ${entry.experimentalAllowed ? "允许" : "不允许"} | ${entry.compatibilityProbeConfigured ? "已配置" : "未配置"} | ${entry.schemaAndTurnProbeConfigured ? "已配置" : "未配置"} |`,
  );
  return [
    "# 外部 Codex App Server 支持范围",
    "",
    "<!-- Generated by packages/cli/scripts/codex-app-server-support.mjs; edit the support manifest. -->",
    "",
    `兼容清单修订：\`${CODEX_APP_SERVER_SUPPORT.revision}\`。`,
    "",
    `生产入口继续使用 \`codex exec --json\`（\`${CODEX_APP_SERVER_FALLBACK_PROTOCOL}\`）。App Server 适配器为独立实验模块，默认关闭，未获生产准入；\`${CODEX_APP_SERVER_FEATURE_FLAG}=1\` 仅控制该模块，不会把现有生产入口切换到 App Server。`,
    "",
    "<!-- prettier-ignore -->",
    "| 精确版本 | 实验允许列表 | schema / 握手 / 移除演练 CI | 固定 schema / turn / 重启与分页 CI |",
    "| --- | --- | --- | --- |",
    ...rows,
    "",
    "CI 配置覆盖 Linux、Windows、macOS。表中“已配置”只说明工作流将执行该探针，不表示已通过；三系统结果必须绑定同一准确提交并另行保留回执。schema / 握手探针不能替代 turn、取消、断流、恢复及历史分页验收。",
    "",
    "固定版本探针使用隔离配置和本地 Responses 模拟服务，覆盖进程重启、会话设置恢复、线程及 turn 游标分页；没有真实模型任务或费用验收。版本通过 --version 显式选择，默认保留 0.160.0，未配置的版本拒绝运行。",
    "",
    "不在清单中的版本、预发布号和无法解析的版本均不获实验允许；新增探针不会自动扩大允许列表或生产准入。自定义 compatibilityMatrix 只影响该适配器实例，runtimeClaims() 的 compatibilitySource 会标记 override，不改写清单支持状态。",
    "",
    "适配器结果的 protocol 表示实际执行协议，support 表示清单状态；提前回退提供 fallbackReason。turn/start 发出后，若提交结果未知或已接受任务后连接失败，错误带有 fallbackSuppressed:true，禁止再走 exec 重复提交。",
    "",
    "维护及核对命令（仓库根目录）：",
    "",
    "```bash",
    "node packages/cli/scripts/codex-app-server-support.mjs --ci",
    'node packages/cli/scripts/codex-app-server-support.mjs --version "codex-cli 0.160.0"',
    "node packages/cli/scripts/codex-app-server-support.mjs --out docs/cli/CODEX_APP_SERVER_SUPPORT.generated.md",
    "node packages/cli/scripts/codex-app-server-support.mjs --check docs/cli/CODEX_APP_SERVER_SUPPORT.generated.md",
    "```",
    "",
    "源码：[兼容清单](../../packages/cli/src/lib/codex-app-server-support.js)、[兼容工作流](../../.github/workflows/codex-app-server-compatibility.yml)。",
    "",
    "官方协议：[OpenAI App Server](https://learn.chatgpt.com/docs/app-server)。官方说明生成 schema 与执行生成命令的 Codex 版本绑定；本表描述本项目支持边界，不宣称上游最新版本。",
    "",
  ].join("\n");
}

function main(argv) {
  const [mode, value, ...extra] = argv;
  if (extra.length) throw new TypeError("Too many arguments");
  if (mode === "--ci" && value === undefined) {
    process.stdout.write(`${JSON.stringify(codexAppServerCiMatrices())}\n`);
  } else if (mode === "--github-output" && value === undefined) {
    if (!process.env.GITHUB_OUTPUT)
      throw new Error("GITHUB_OUTPUT is required");
    for (const [key, matrix] of Object.entries(codexAppServerCiMatrices())) {
      appendFileSync(
        process.env.GITHUB_OUTPUT,
        `${key}=${JSON.stringify(matrix)}\n`,
      );
    }
  } else if (mode === "--version" && value) {
    process.stdout.write(
      `${JSON.stringify(getCodexAppServerSupport(value))}\n`,
    );
  } else if ((mode === "--out" || mode === "--check") && value) {
    const path = resolve(value);
    const document = renderCodexAppServerSupport();
    if (mode === "--check") {
      if (readFileSync(path, "utf8").replaceAll("\r\n", "\n") !== document) {
        throw new Error("Codex App Server support document is out of date");
      }
    } else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, document, "utf8");
    }
  } else {
    throw new TypeError(
      "usage: codex-app-server-support.mjs --ci | --github-output | --version <version> | --out <path> | --check <path>",
    );
  }
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  }
}
