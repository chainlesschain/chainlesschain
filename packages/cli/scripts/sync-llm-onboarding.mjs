import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../../../", import.meta.url);
const source = new URL(
  "packages/cli/src/lib/llm-onboarding-catalog.json",
  root,
);
const raw = readFileSync(source, "utf8").replaceAll("\r\n", "\n");
const catalog = JSON.parse(raw);
if (
  catalog.schema !== "chainlesschain.llm-onboarding-catalog/v1" ||
  !Array.isArray(catalog.providers) ||
  !catalog.providers.length
)
  throw new Error("Invalid onboarding catalog");
const ids = new Set();
for (const entry of catalog.providers) {
  if (
    typeof entry.id !== "string" ||
    !entry.id ||
    ids.has(entry.id) ||
    typeof entry.label !== "string" ||
    typeof entry.baseUrl !== "string" ||
    typeof entry.defaultModel !== "string" ||
    typeof entry.needsKey !== "boolean" ||
    (entry.cliLabel !== undefined && typeof entry.cliLabel !== "string") ||
    (entry.visionModel !== undefined &&
      typeof entry.visionModel !== "string") ||
    (entry.isProxy !== undefined && typeof entry.isProxy !== "boolean")
  )
    throw new Error("Invalid onboarding provider");
  ids.add(entry.id);
}
const sourceSha256 = createHash("sha256").update(raw).digest("hex");
const providers = catalog.providers.filter(
  (entry) => !entry.isProxy && entry.id !== "custom",
);
const vendor = new URL(
  "packages/vscode-extension/src/vendor/llm-onboarding-presets.json",
  root,
);
const document =
  JSON.stringify(
    {
      ...catalog,
      sourceSha256,
      sourceDigestBasis: "utf8-lf",
      providers,
    },
    null,
    2,
  ) + "\n";

const javaPath = new URL(
  "packages/jetbrains-plugin/src/main/java/com/chainlesschain/ide/LlmConfig.java",
  root,
);
const java = readFileSync(javaPath, "utf8").replaceAll("\r\n", "\n");
const begin = "    // BEGIN GENERATED LLM ONBOARDING PRESETS";
const end = "    // END GENERATED LLM ONBOARDING PRESETS";
const start = java.indexOf(begin);
const finish = java.indexOf(end);
if (start < 0 || finish < start)
  throw new Error("Missing Java onboarding markers");
const quote = (value) => JSON.stringify(value);
const generated = [
  begin,
  "    // Generated by packages/cli/scripts/sync-llm-onboarding.mjs; edit the canonical JSON.",
  `    public static final String PRESET_CATALOG_SHA256 = ${quote(sourceSha256)};`,
  "    public static final Preset[] PRESETS = {",
  ...providers.map(
    (entry, index) =>
      `        new Preset(${[entry.id, entry.label, entry.baseUrl, entry.defaultModel].map(quote).join(", ")}, ${entry.needsKey}, ${quote(entry.visionModel || "")})${index < providers.length - 1 ? "," : ""}`,
  ),
  "    };",
  end,
].join("\n");
const javaDocument =
  java.slice(0, start) + generated + java.slice(finish + end.length);
const outputs = [
  [vendor, document],
  [javaPath, javaDocument],
];
if (process.argv.includes("--check")) {
  for (const [path, expected] of outputs) {
    let actual = "";
    try {
      actual = readFileSync(path, "utf8").replaceAll("\r\n", "\n");
    } catch {
      /* missing is stale */
    }
    if (actual !== expected)
      throw new Error(
        `Onboarding presets are stale: ${fileURLToPath(path)}; run node scripts/sync-llm-onboarding.mjs`,
      );
  }
  console.log("CLI / VS Code / JetBrains onboarding presets are synchronized.");
} else {
  for (const [path, content] of outputs) writeFileSync(path, content, "utf8");
  console.log("Synchronized VS Code and JetBrains onboarding presets.");
}
