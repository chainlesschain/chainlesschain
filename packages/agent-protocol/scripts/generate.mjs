function modelFieldName(field, language) {
  const keywords = language === "swift" ? swiftKeywords : kotlinKeywords;
  return keywords.has(field) ? `\`${field}\`` : field;
}

function renderKotlin() {
  const models = Object.entries(schema.$defs)
    .filter(
      ([, definition]) =>
        definition.type === "object" &&
        definition.properties &&
        !definition.oneOf &&
        !definition.allOf,
    )
    .map(([name, definition]) => {
      const required = new Set(definition.required || []);
      const fields = Object.entries(definition.properties).map(
        ([field, child]) => {
          const optional = !required.has(field);
          const type = modelType(child, "kotlin");
          return `    val ${modelFieldName(field, "kotlin")}: ${optional && !type.endsWith("?") ? `${type}?` : type}${optional ? " = null" : ""}`;
        },
      );
      return `data class ${name}(\n${fields.join(",\n")}\n)`;
    })
    .join("\n\n");
  return `// AUTO-GENERATED by @chainlesschain/agent-protocol. DO NOT EDIT.
package com.chainlesschain.agent.protocol.generated

const val CC_AGENT_PROTOCOL_VERSION: Int = ${protocol.version}
const val CC_AGENT_PROTOCOL_MIN_VERSION: Int = ${protocol.minimumCompatibleVersion}
const val CC_AGENT_PROTOCOL_SCHEMA_DIGEST: String = "${digest}"
typealias JSONValue = Any?

${models}
`;
}

function renderSwift() {
  const models = Object.entries(schema.$defs)
    .filter(
      ([, definition]) =>
        definition.type === "object" &&
        definition.properties &&
        !definition.oneOf &&
        !definition.allOf,
    )
    .map(([name, definition]) => {
      const required = new Set(definition.required || []);
      const fields = Object.entries(definition.properties).map(
        ([field, child]) => {
          const optional = !required.has(field);
          const type = modelType(child, "swift");
          return `    public let ${modelFieldName(field, "swift")}: ${optional && !type.endsWith("?") ? `${type}?` : type}`;
        },
      );
      return `public struct ${name}: Codable, Sendable {\n${fields.join("\n")}\n}`;
    })
    .join("\n\n");
  return `// AUTO-GENERATED by @chainlesschain/agent-protocol. DO NOT EDIT.
import Foundation

public let ccAgentProtocolVersion = ${protocol.version}
public let ccAgentProtocolMinimumVersion = ${protocol.minimumCompatibleVersion}
public let ccAgentProtocolSchemaDigest = "${digest}"
public indirect enum JSONValue: Codable, Sendable {
    case null
    case bool(Bool)
    case number(Double)
    case string(String)
    case array([JSONValue])
    case object([String: JSONValue])

    public init(from decoder: Decoder) throws {
        let container = try decoder.singleValueContainer()
        if container.decodeNil() { self = .null }
        else if let value = try? container.decode(Bool.self) { self = .bool(value) }
        else if let value = try? container.decode(Double.self) { self = .number(value) }
        else if let value = try? container.decode(String.self) { self = .string(value) }
        else if let value = try? container.decode([JSONValue].self) { self = .array(value) }
        else { self = .object(try container.decode([String: JSONValue].self)) }
    }

    public func encode(to encoder: Encoder) throws {
        var container = encoder.singleValueContainer()
        switch self {
        case .null: try container.encodeNil()
        case .bool(let value): try container.encode(value)
        case .number(let value): try container.encode(value)
        case .string(let value): try container.encode(value)
        case .array(let value): try container.encode(value)
        case .object(let value): try container.encode(value)
        }
    }
}

${models}
`;
}

