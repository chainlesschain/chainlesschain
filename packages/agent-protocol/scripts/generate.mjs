function refName(value) {
  return value.replace("#/$defs/", "");
}

function tsType(node = {}) {
  if (node.$ref) return refName(node.$ref);
  if (Object.hasOwn(node, "const")) return JSON.stringify(node.const);
  if (node.enum)
    return node.enum.map((value) => JSON.stringify(value)).join(" | ");
  if (node.oneOf) return node.oneOf.map(tsType).join(" | ");
  if (node.anyOf) return node.anyOf.map(tsType).join(" | ");
  if (node.allOf)
    return node.allOf.map((part) => `(${tsType(part)})`).join(" & ");
  if (Array.isArray(node.type))
    return node.type.map((type) => tsType({ ...node, type })).join(" | ");
  if (node.type === "null") return "null";
  if (node.type === "boolean") return "boolean";
  if (node.type === "number" || node.type === "integer") return "number";
  if (node.type === "string") return "string";
  if (node.type === "array") return `Array<${tsType(node.items || {})}>`;
  if (node.type === "object" || node.properties || node.additionalProperties) {
    const required = new Set(node.required || []);
    const properties = Object.entries(node.properties || {}).map(
      ([name, value]) =>
        `${JSON.stringify(name)}${required.has(name) ? "" : "?"}: ${tsType(value)};`,
    );
    if (node.additionalProperties && node.additionalProperties !== false) {
      properties.push(`[key: string]: ${tsType(node.additionalProperties)};`);
    }
    return `{ ${properties.join(" ")} }`;
  }
  return "unknown";
}

