function modelFieldName(field, language) {
  const keywords = language === "swift" ? swiftKeywords : kotlinKeywords;
  return keywords.has(field) ? `\`${field}\`` : field;
}

function renderKotlin() {
  const models = Object.entries(schema.$defs)
    .filter(
      ([, definition]) =>
        definition.type === "object" &&
        definition.properties &&
        !definition.oneOf &&
        !definition.allOf,
    )
    .map(([name, definition]) => {
      const required = new Set(definition.required || []);
      const fields = Object.entries(definition.properties).map(
        ([field, child]) => {
          const optional = !required.has(field);
          const type = modelType(child, "kotlin");
          return `    val ${modelFieldName(field, "kotlin")}: ${optional && !type.endsWith("?") ? `${type}?` : type}${optional ? " = null" : ""}`;
        },
      );
      return `data class ${name}(\n${fields.join(",\n")}\n)`;
    })
    .join("\n\n");
  return `// AUTO-GENERATED by @chainlesschain/agent-protocol. DO NOT EDIT.
package com.chainlesschain.agent.protocol.generated

const val CC_AGENT_PROTOCOL_VERSION: Int = ${protocol.version}
const val CC_AGENT_PROTOCOL_MIN_VERSION: Int = ${protocol.minimumCompatibleVersion}
const val CC_AGENT_PROTOCOL_SCHEMA_DIGEST: String = "${digest}"
typealias JSONValue = Any?

${models}
`;
}

