import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {captureHostDiagnostics} from '../../packages/jetbrains-plugin/scripts/run-ui-host-journey.mjs';
import {collectIdeJourneyArtifacts} from '../../scripts/ide-journey-evidence.mjs';
const root=path.dirname(fileURLToPath(import.meta.url));
const fixture=fs.mkdtempSync(path.join(root,'raw-log-contract-'));
const sandbox=path.join(fixture,'sandbox'),capture=path.join(fixture,'capture'),archive=path.join(fixture,'archive');
fs.mkdirSync(path.join(sandbox,'IC-2024.2','log_runIdeForUiTests'),{recursive:true});fs.mkdirSync(capture);
const original=Buffer.concat([Buffer.from([255,254]),Buffer.alloc(300000,65),Buffer.from('\r\n')]);
fs.writeFileSync(path.join(sandbox,'IC-2024.2','log_runIdeForUiTests','idea.log'),original);
fs.writeFileSync(path.join(capture,'host-events.jsonl'),JSON.stringify({schema:'chainlesschain.ui-event-diagnostic/v1',stage:'RECEIVED',type:'approval_request'})+'\n');
const captured=captureHostDiagnostics(sandbox,capture);
const collected=collectIdeJourneyArtifacts([capture],archive);
const entry=collected.records.find(r=>r.path.endsWith('.log.bin'));
const digest=b=>crypto.createHash('sha256').update(b).digest('hex');
const archived=fs.readFileSync(path.join(archive,entry.path));
const report={scope:'Synthetic original bytes through actual driver and actual evidence collector; not a real IDE run',fixture,captured,collectorIncidents:collected.incidents,originalBytes:original.length,archivedBytes:archived.length,originalSha256:digest(original),archivedSha256:digest(archived),entry,pass:captured.complete&&collected.incidents.length===0&&original.equals(archived)&&!entry.truncated&&!entry.redacted};
fs.writeFileSync(path.join(root,'diagnostics-raw-byte-contract.json'),JSON.stringify(report,null,2));
const junit=path.resolve('packages/jetbrains-plugin/build/test-results/test/TEST-com.chainlesschain.ide.UiEventDiagnosticsTest.xml');
fs.copyFileSync(junit,path.join(root,'diagnostics-junit.xml'));
console.log(JSON.stringify({pass:report.pass,originalBytes:report.originalBytes,archivedBytes:report.archivedBytes,sha256:report.originalSha256}));
if(!report.pass)process.exitCode=1;
